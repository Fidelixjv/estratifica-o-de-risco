/** Atalho para evitar repetição dos campos neutros da base de famílias. */
function cidadao(dados: Partial<Cidadao> & Pick<Cidadao, 'id' | 'nome' | 'dataNascimento' | 'sexo'>): Cidadao {
  return {
    situacaoOcupacional: 'ocupado',
    alfabetizacao: 'alfabetizado',
    restricaoDomiciliar: false,
    deficienciaFisica: false,
    deficienciaMental: false,
    desnutricaoGrave: false,
    drogadicao: false,
    diabetes: false,
    pressaoArterial: null,
    situacoes: [],
    ...dados,
  }
}

